import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import pg from 'pg';

const backendDir = '/var/www/lulu-growth-os/backend';
const nginxInclude = '/etc/nginx/conf.d/lulu-managed-domains.conf';
const webRoot = '/var/www/lulu-ai.cn/html';
const baseHost = String(process.env.LULU_MANAGED_WEBSITE_HOSTNAME ?? '').trim().toLowerCase().replace(/\.$/, '');
const certbotEmail = String(process.env.LULU_DOMAIN_CERTBOT_EMAIL ?? '').trim();
const hostnamePattern = /^(?=.{1,253}$)([a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;

if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required');

const db = new pg.Client({
  connectionString: process.env.DATABASE_URL,
  ...(process.env.DATABASE_SSL === 'true' ? { ssl: { rejectUnauthorized: false } } : {}),
});

const nginxProxyHeaders = `
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_read_timeout 60s;
        proxy_buffering off;`;

function certificateExists(hostname) {
  return fs.existsSync(`/etc/letsencrypt/live/${hostname}/fullchain.pem`)
    && fs.existsSync(`/etc/letsencrypt/live/${hostname}/privkey.pem`);
}

function runCertbot(hostname) {
  const args = [
    'certonly', '--webroot', '-w', webRoot,
    '--non-interactive', '--keep-until-expiring', '--agree-tos',
    ...(certbotEmail ? ['--email', certbotEmail] : ['--register-unsafely-without-email']),
    '-d', hostname,
  ];
  try {
    execFileSync('/usr/bin/certbot', args, { stdio: 'inherit', timeout: 120_000 });
    return certificateExists(hostname);
  } catch (error) {
    console.warn(`Certificate issuance skipped for ${hostname}: ${error instanceof Error ? error.message : String(error)}`);
    return certificateExists(hostname);
  }
}

function serverBlock(hostname, https) {
  const certificate = `/etc/letsencrypt/live/${hostname}`;
  return `server {
    listen ${https ? '443 ssl' : '80'};
    ${https ? `ssl_certificate ${certificate}/fullchain.pem;\n    ssl_certificate_key ${certificate}/privkey.pem;\n    include /etc/letsencrypt/options-ssl-nginx.conf;\n    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem;` : ''}
    server_name ${hostname};
    client_max_body_size 5M;

    location ^~ /api/ {
        proxy_pass http://127.0.0.1:3000;
${nginxProxyHeaders}
    }

    location ^~ /.well-known/acme-challenge/ {
        root ${webRoot};
    }

    location / {
        proxy_pass http://127.0.0.1:3000/api/v1/public/storefront/host;
${nginxProxyHeaders}
    }
}
`;
}

await db.connect();
try {
  const result = await db.query(`
    SELECT DISTINCT lower(d.hostname) AS hostname
    FROM workspace_site_domains d
    JOIN workspace_sites s ON s.id=d.site_id
    -- A verified domain is routable before the first publication as well. The
    -- storefront endpoint serves Lulu's neutral template until the same site
    -- record is published, so DNS and certificates never need to be re-bound.
    WHERE d.status='verified' AND s.provider='managed' AND s.status <> 'disconnected'
    ORDER BY hostname`);
  const domains = result.rows
    .map((row) => String(row.hostname).trim().replace(/\.$/, '').toLowerCase())
    .filter((hostname) => hostnamePattern.test(hostname))
    .filter((hostname) => hostname !== baseHost && hostname !== `www.${baseHost}`);

  // Make verified domains reachable over HTTP first. This also gives ACME
  // HTTP-01 a stable challenge path before an individual certificate exists.
  let blocks = domains.map((hostname) => serverBlock(hostname, false));
  fs.mkdirSync('/etc/nginx/conf.d', { recursive: true });
  fs.writeFileSync(`${nginxInclude}.tmp`, `# Generated by Lulu managed-domain reconciler.\n${blocks.join('\n')}`);
  fs.renameSync(`${nginxInclude}.tmp`, nginxInclude);
  execFileSync('/usr/sbin/nginx', ['-t'], { stdio: 'inherit' });
  execFileSync('/usr/bin/systemctl', ['reload', 'nginx']);

  const certificateHosts = [];
  for (const hostname of domains) {
    if (!certificateExists(hostname) && !runCertbot(hostname)) continue;
    certificateHosts.push(hostname);
  }

  blocks = domains.map((hostname) => serverBlock(hostname, false));
  blocks.push(...certificateHosts.map((hostname) => serverBlock(hostname, true)));
  fs.writeFileSync(`${nginxInclude}.tmp`, `# Generated by Lulu managed-domain reconciler.\n${blocks.join('\n')}`);
  fs.renameSync(`${nginxInclude}.tmp`, nginxInclude);
  execFileSync('/usr/sbin/nginx', ['-t'], { stdio: 'inherit' });
  execFileSync('/usr/bin/systemctl', ['reload', 'nginx']);
  console.log(JSON.stringify({ verifiedDomains: domains, httpsDomains: certificateHosts }));
} finally {
  await db.end();
}
